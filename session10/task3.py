#Given a tuple scores = (120, 85, 150, 200, 85, 120), write code to count how many times the score 120 appears in the tuple and print the result.<br><br><em><strong>Hint:</strong> Use the tuple's count() method.</em>
scores = (120, 85, 150, 200, 85, 120)

